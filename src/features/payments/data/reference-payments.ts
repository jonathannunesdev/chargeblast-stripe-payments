export function referenceTimestamp(hours: number, minutes: number): number {
  const { year, month, day } = REFERENCE_DATE;
  return new Date(year, month, day, hours, minutes).getTime();
}

export function getReferencePayments(): Payment[] {
  return ROWS.map((row) => ({
    id: row.id,
    amount: row.amount,
    currency: row.currency,
    status: row.status,
    paymentMethod: {
      type: "card",
      brand: row.brand,
      last4: row.last4,
      wallet: row.wallet,
    },
    description: "Subscription update",
    customerEmail: row.email,
    created: referenceTimestamp(...row.time),
    refundedAt: null,
    declineReason: row.declineReason,
  }));
}
